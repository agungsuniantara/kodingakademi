#include <iostream>

using namespace std;

int main(){
    cout<<"1   ^ 0 = "<<(1^0)<<endl;
    cout<<"15  ^ 4 = "<<(15^4)<<endl;
    cout<<"19 << 1 = "<<(19<<1)<<endl;
    cout<<"19 << 2 = "<<(19<<2)<<endl;
    cout<<"19 << 3 = "<<(19<<3)<<endl;
    cout<<"19 >> 1 = "<<(19>>1)<<endl;
    cout<<"19 >> 2 = "<<(19>>2)<<endl;
    cout<<"19 >> 3 = "<<(19>>3)<<endl;
    return 0;
}