# Membuat set
my_set = {1, 2, 3, 4, 5}

# Menampilkan set
print("Set:", my_set)

# Tidak dapat mengakses elemen set menggunakan indeks
# my_set[0] tidak akan berfungsi

# Menambahkan elemen baru ke set
my_set.add(6)
print("Set setelah ditambahkan:", my_set)

# Menghapus elemen dari set
my_set.remove(3)
print("Set setelah dihapus:", my_set)
