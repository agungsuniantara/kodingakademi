# Membuat list
my_list = [1, 2, 3, 4, 5]

# Menampilkan list
print("List:", my_list)

# Mengakses elemen list menggunakan indeks
print("Elemen ke-3:", my_list[2])

# Menambahkan elemen baru ke list
my_list.append(6)
print("List setelah ditambahkan:", my_list)

# Mengubah nilai elemen pada indeks tertentu
my_list[0] = 10
print("List setelah diubah:", my_list)

# Menghapus elemen dari list
my_list.remove(3)
print("List setelah dihapus:", my_list)
