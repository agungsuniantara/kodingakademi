public class App {
    public static void main(String[] args) throws Exception {
        // deklarasi variabel
        int angka = 10;
        String nama = "catherine";

        System.out.println(angka);
        System.out.println(nama);

        // deklarasi variabel terpisah
        int angka1, angka2;

        angka1 = 100;
        angka2 = 20;

        System.out.println(angka1);
        System.out.println(angka2);

        // tipe data

        // integer
        int contoh1 = 100;
        System.out.println(contoh1);

        // float
        float contoh2 = 200.22f;
        System.out.println(contoh2);

        // double
        double contoh3 = 300.11;
        System.out.println(contoh3);

        // char
        char kata = 'a';
        System.out.println(kata);

        // string
        String alamat = "denpasar";
        System.out.println("alamat = " + alamat);

        // boolean
        boolean benar = true;
        System.out.println(benar);

        // challange
        System.out.println("data diri : ");

        String nama2 = "agung";
        int umur = 25;
        String alamat2 = "canggu";

        System.out.println("nama = " + nama2);
        System.out.println("umur = " + umur);
        System.out.println("alamat = " + alamat2);
    }
}
