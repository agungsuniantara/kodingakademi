# membulatkan angka ke bawah (floor)
import math

print("math.floor(-39.37) : ", math.floor(-38.11)) #kalo plus turun, kalo min naik
print("math.floor(88.12) : ", math.floor(88.12))
print("math.floor(11.72) : ", math.floor(11.72))
print("math.floor(111) : ", math.floor(111))
print("math.floor(math.pi) : ", math.floor(math.pi))