import math

# max 
data1 = [10, 20, 30]
data2 = [10, 20, 30, 40]
print(max(data1))
print(max(data1, data2, key = len))

# min
print(min(data1))
print(min(5, -7))

# pow
print(pow(2, 3))

# round
print(round(1.55555, 3))

# abs
print(abs(-90))

# sqrt
print(math.sqrt(144))

# ceil & floor

print(math.ceil(11.22))
print(math.floor(11.22))

# sin , cos, tan

print(math.sin(90))
print(math.cos(90))
print(math.tan(90))

# exponential

print(math.exp(10))

