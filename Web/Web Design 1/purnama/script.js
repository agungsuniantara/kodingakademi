// Fungsi untuk menampilkan deskripsi
function tampilkanDeskripsi(element) {
  var deskripsi = element.querySelector(".deskripsi");
  deskripsi.style.opacity = "1";
}

// Fungsi untuk menyembunyikan deskripsi
function sembunyikanDeskripsi(element) {
  var deskripsi = element.querySelector(".deskripsi");
  deskripsi.style.opacity = "0";
}
